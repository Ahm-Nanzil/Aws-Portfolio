<script>
$(document).ready(function() {
    $('#ajax-contact-form').on('submit', function(e) {
        e.preventDefault();

        var $form = $(this);
        var $response = $form.find('.wpcf7-response-output');

        $.ajax({
            url: 'email.php',       // your PHP mailer
            type: 'POST',
            data: $form.serialize(),
            beforeSend: function() {
                $response.html('Sending...');
            },
            success: function(data) {
                if(data.trim() === 'success') {
                    $response.html('<p class="wpcf7-mail-sent-ok">Thank you! Your message has been sent.</p>');
                    $form[0].reset();
                } else {
                    $response.html('<p class="wpcf7-mail-sent-ng">Error: ' + data + '</p>');
                }
            },
            error: function(xhr, status, error) {
                $response.html('<p class="wpcf7-mail-sent-ng">AJAX error: ' + error + '</p>');
            }
        });
    });
});
</script>


